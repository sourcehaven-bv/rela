func scanSource(t *testing.T, src string) []finding {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "x.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	return findings(fset, file)
}

func TestFindings(t *testing.T) {
	longDoc := strings.Repeat("// line\n", docCap+1)
	okDoc := strings.Repeat("// line\n", docCap)
	tests := []struct {
		name string
		src  string
		want int
	}{
		{"body comment", "package p\nfunc f() {\n\t// explain\n\t_ = 1\n}\n", 1},
		{"trailing body comment", "package p\nfunc f() {\n\t_ = 1 // explain\n}\n", 1},
		{"closure comment", "package p\nvar g = func() {\n\t// explain\n}\n", 1},
		{"nested closure counted once", "package p\nfunc f() {\n\tg := func() {\n\t\t// explain\n\t}\n\t_ = g\n}\n", 1},
		{"directive in body", "package p\nfunc f() {\n\t//nolint:gosec\n\t_ = 1\n}\n", 0},
		{"coverage-ignore", "package p\nfunc f() {\n\t// coverage-ignore: defensive\n\t_ = 1\n}\n", 0},
		{"bare nolint", "package p\nfunc f() {\n\t// nolint\n\t_ = 1\n}\n", 0},
		{"why with reason", "package p\nfunc f() {\n\t// why: library bug 42\n\t_ = 1\n}\n", 0},
		{"why without reason", "package p\nfunc f() {\n\t// why:\n\t_ = 1\n}\n", 1},
		{"nosec with justification", "package p\nfunc f() {\n\t// #nosec G705 -- not an HTML sink:\n\t// escaped upstream.\n\t_ = 1\n}\n", 0},
		{"coverage block with reason", "package p\nfunc f() {\n\t// coverage-ignore-start: defensive: never\n\t// fails in practice\n\t_ = 1\n\t// coverage-ignore-end\n}\n", 0},
		{"nosemgrep", "package p\nfunc f() {\n\t// nosemgrep: rule.id\n\t_ = 1\n}\n", 0},
		{"short doc", "package p\n" + okDoc + "func f() {}\n", 0},
		{"long doc", "package p\n" + longDoc + "func f() {}\n", 1},
		{"long doc with directives and blanks", "package p\n" + okDoc + "//\n//go:noinline\nfunc f() {}\n", 0},
		{"comment outside body", "package p\n// T is a thing.\ntype T struct {\n\t// A is a.\n\tA int\n}\n", 0},
		{"generated file", "// Code generated by x. DO NOT EDIT.\n\npackage p\nfunc f() {\n\t// explain\n}\n", 0},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := len(scanSource(t, tc.src)); got != tc.want {
				t.Errorf("findings = %d, want %d", got, tc.want)
			}
		})
	}
}

func TestCompare(t *testing.T) {
	found := map[string][]finding{"a.go": {{kind: kindBody}, {kind: kindBody}}}
	tests := []struct {
		name     string
		counts   map[string]int
		baseline map[string]int
		wantLen  int
	}{
		{"equal", map[string]int{"a.go": 2}, map[string]int{"a.go": 2}, 0},
		{"new comment fails", map[string]int{"a.go": 2}, map[string]int{"a.go": 1}, 3},
		{"new file fails", map[string]int{"a.go": 2}, map[string]int{}, 3},
		{"improvement does not fail", map[string]int{}, map[string]int{"a.go": 2}, 0},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := compare(tc.counts, tc.baseline, found); len(got) != tc.wantLen {
				t.Errorf("problems = %v, want %d", got, tc.wantLen)
			}
		})
	}
}

func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, content := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

const commentedFunc = "package p\nfunc f() {\n\t// explain\n}\n"

func TestScanTreeSkipsTestsAndVendoredDirs(t *testing.T) {
	root := writeTree(t, map[string]string{
		"a.go":               commentedFunc,
		"a_test.go":          commentedFunc,
		"frontend/b.go":      commentedFunc,
		"testdata/c.go":      commentedFunc,
		"internal/sub/d.go":  commentedFunc,
		"internal/sub/e.txt": "not go",
	})
	got, err := scanTree(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 2 || len(got["a.go"]) != 1 || len(got["internal/sub/d.go"]) != 1 {
		t.Errorf("scanTree = %v, want only a.go and internal/sub/d.go", got)
	}
}

func TestScanTreeReportsParseError(t *testing.T) {
	root := writeTree(t, map[string]string{"bad.go": "package p\nfunc {"})
	if _, err := scanTree(root); err == nil {
		t.Error("want a parse error")
	}
}

func TestRunAgainstBaseline(t *testing.T) {
	root := writeTree(t, map[string]string{"a.go": commentedFunc, baselinePath: "{}"})
	if err := run(root, false); err == nil {
		t.Fatal("new finding above an empty baseline must fail")
	}
	if err := run(root, true); err != nil {
		t.Fatalf("update: %v", err)
	}
	if err := run(root, false); err != nil {
		t.Fatalf("after update: %v", err)
	}
	if err := os.WriteFile(filepath.Join(root, "a.go"), []byte("package p\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := run(root, false); err != nil {
		t.Fatalf("an improvement must only note, got: %v", err)
	}
}

