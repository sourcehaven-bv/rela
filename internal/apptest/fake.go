// faker generates values from one seed. Every value it returns depends only
// on the seed and on the calls made before it, so a case that makes the same
// calls gets the same values on every run with the same seed.
//
// It knows the schema: [faker.value] generates a value for a declared
// property that passes the property's own checks (type, enum values, min and
// max, scale, date format). It does not know validation rules, write rules or
// automations; a value one of those rejects is the case's to override.
type faker struct {
	f    *gofakeit.Faker
	rng  *rand.Rand
	now  func() time.Time
	meta *metamodel.Metamodel
	// files counts the attachment names handed out, so two file properties
	// of one entity get different names.
	files int
}

// pcgStream derives the faker's second PCG word from the seed, so it does
// not draw the same stream as the case's math.random.
const pcgStream = 0x9e3779b97f4a7c15

// fakerSeed maps seed to gofakeit's: gofakeit takes 0 to mean a random
// seed, which would make that one case seed unreproducible.
func fakerSeed(seed uint64) uint64 {
	if seed == 0 {
		return math.MaxUint64
	}
	return seed
}

func newFaker(seed uint64, now func() time.Time, meta *metamodel.Metamodel) *faker {
	return &faker{
		f: gofakeit.New(fakerSeed(seed)),
		// Reproducible test data, not secrets.
		rng:  rand.New(rand.NewPCG(seed, seed^pcgStream)), //nolint:gosec // see above
		now:  now,
		meta: meta,
	}
}

// intRange returns an int in [lo, hi]. hi below lo returns lo.
func (g *faker) intRange(lo, hi int) int {
	if hi <= lo {
		return lo
	}
	return lo + g.rng.IntN(hi-lo+1)
}

// pick returns one of values, which must not be empty.
func (g *faker) pick(values []string) string { return values[g.rng.IntN(len(values))] }

// generatedFile is the content of a generated attachment.
const generatedFile = "generated by rela test\n"

// value generates a value for property prop of entityType. It fails for an
// unknown type or property, and for a kind it cannot generate.
func (g *faker) value(entityType, prop string) (any, error) {
	def, ok := g.meta.Entities[entityType]
	if !ok {
		return nil, fmt.Errorf("unknown entity type %q", entityType)
	}
	pd, ok := def.Properties[prop]
	if !ok {
		return nil, fmt.Errorf("%s has no property %q", entityType, prop)
	}
	return g.propertyValue(prop, &pd)
}

// propertyValue generates a value for one property definition. A list
// property gets a list of one value.
func (g *faker) propertyValue(name string, pd *metamodel.PropertyDef) (any, error) {
	v, err := g.scalar(name, pd)
	if err != nil {
		return nil, err
	}
	if pd.List && pd.Type != metamodel.PropertyTypeFile {
		return []any{v}, nil
	}
	return v, nil
}

// dateSpan is how many days before the clock generated dates fall, and
// how far around it t.fake.date falls by default.
const dateSpan = 365

// minutesPerDay converts dateSpan to the minutes a generated date is drawn from.
const minutesPerDay = 24 * 60

func (g *faker) scalar(name string, pd *metamodel.PropertyDef) (any, error) {
	if values := metamodel.EnumValues(*pd, g.meta); len(values) > 0 {
		return g.pick(values), nil
	}
	switch pd.Type {
	case metamodel.PropertyTypeString, "":
		return g.f.Sentence(), nil
	case metamodel.PropertyTypeInteger:
		lo, hi := g.bounds(pd)
		return int64(g.intRange(lo, hi)), nil
	case metamodel.PropertyTypeDecimal:
		return g.decimal(pd), nil
	case metamodel.PropertyTypeBoolean:
		return g.rng.IntN(2) == 1, nil
	case metamodel.PropertyTypeDate, metamodel.PropertyTypeDatetime:
		// In the past year, so a rule like "start <= today()" holds; a value
		// in the future is the case's to set.
		offset := time.Duration(g.intRange(-dateSpan*minutesPerDay, 0)) * time.Minute
		t := g.now().UTC().Add(offset).Truncate(time.Second)
		return t.Format(pd.GetDateFormat()), nil
	case metamodel.PropertyTypeRrule:
		return "FREQ=WEEKLY;BYDAY=" + g.pick([]string{"MO", "TU", "WE", "TH", "FR"}), nil
	case metamodel.PropertyTypeFile:
		g.files++
		return fmt.Sprintf("generated-%d.txt", g.files), nil
	case metamodel.PropertyTypeEnum:
		return nil, fmt.Errorf("property %s is an enum with no values", name)
	case metamodel.PropertyTypeExternalRef:
		return nil, fmt.Errorf("property %s is an external_ref; rela test does not generate those, set it", name)
	}
	if _, custom := g.meta.Types[pd.Type]; custom {
		return g.f.Sentence(), nil
	}
	return nil, fmt.Errorf("property %s has type %q, which rela test cannot generate", name, pd.Type)
}

// Default bounds for a generated number without min or max.
const (
	defaultMin = 1
	defaultMax = 100
)

// bounds returns the inclusive range a generated number falls in.
func (g *faker) bounds(pd *metamodel.PropertyDef) (lo, hi int) {
	lo, hi = defaultMin, defaultMax
	if pd.Min != nil {
		lo = *pd.Min
		if pd.Max == nil {
			hi = lo + defaultMax
		}
	}
	if pd.Max != nil {
		hi = *pd.Max
		if pd.Min == nil && hi < lo {
			lo = hi - defaultMax
		}
	}
	return lo, hi
}

// defaultScale is the digits after the point of a decimal without a scale.
const defaultScale = 2

// decimal returns a decimal string within the property's bounds and scale.
// The fraction is added only below the upper bound, so it never exceeds it.
func (g *faker) decimal(pd *metamodel.PropertyDef) string {
	lo, hi := g.bounds(pd)
	scale := defaultScale
	if pd.Scale != nil {
		scale = *pd.Scale
	}
	whole := g.intRange(lo, hi)
	if scale == 0 || whole == hi {
		return strconv.Itoa(whole)
	}
	digits := make([]byte, scale)
	for i := range digits {
		digits[i] = "0123456789"[g.rng.IntN(10)]
	}
	if whole < 0 {
		// -3.25 lies below -3; keep it inside [lo, hi] by moving up one.
		whole++
		if whole == 0 {
			return "-0." + string(digits)
		}
	}
	return fmt.Sprintf("%d.%s", whole, digits)
}

// fill sets every required property of entityType that props does not
// set, in property-name order so the generated values do not depend on map
// order. A property with a default gets the default. Computed and rollup
// properties are left to the write path. File properties are not set: it
// returns their names, and the caller attaches a file to each.
func (g *faker) fill(entityType string, props map[string]any) ([]string, error) {
	def, ok := g.meta.Entities[entityType]
	if !ok {
		return nil, fmt.Errorf("unknown entity type %q", entityType)
	}
	var files []string
	names := make([]string, 0, len(def.Properties))
	for name := range def.Properties {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		pd := def.Properties[name]
		if _, set := props[name]; set || !pd.Required || pd.Computed != "" || pd.Rollup != nil {
			continue
		}
		// The declared default first: a state machine's initial value is the
		// only one a create may enter at.
		if d := metamodel.DeclaredDefault(pd, g.meta); d != "" {
			props[name] = d
			continue
		}
		if pd.Type == metamodel.PropertyTypeFile {
			// A file value is set only by attaching a file.
			files = append(files, name)
			continue
		}
		v, err := g.propertyValue(name, &pd)
		if err != nil {
			return nil, fmt.Errorf("generate %s.%s: %w", entityType, name, err)
		}
		props[name] = v
	}
	return files, nil
}

// manualID returns a generated id for a type whose ids are given by hand,
// or "" when the store assigns them.
func (g *faker) manualID(entityType string) string {
	def := g.meta.Entities[entityType]
	// "string" is the deprecated spelling of "manual".
	if def.IDType != metamodel.IDTypeManual && def.IDType != "string" {
		return ""
	}
	prefix := def.IDPrefix
	if prefix == "" && len(def.IDPrefixes) > 0 {
		prefix = def.IDPrefixes[0]
	}
	if prefix == "" {
		prefix = strings.ToUpper(entityType)
	}
	const idDigits = 1_000_000
	return fmt.Sprintf("%s-%06d", prefix, g.rng.IntN(idDigits))
}
